/* 分享卡内容、字号和旧档兼容检查，不依赖截图识字。 */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm'), assert = require('assert/strict');
const dir = path.join(__dirname, '..'), store = {};
const ctx = {console, Math, Date, JSON, localStorage:{getItem:k=>store[k]||null,setItem:(k,v)=>store[k]=v}};
ctx.window = ctx; vm.createContext(ctx);
const run = p => vm.runInContext(fs.readFileSync(path.join(dir,p),'utf8'),ctx,{filename:p});
const files = [...fs.readFileSync(path.join(dir,'index.html'),'utf8').matchAll(/<script src="([^"]+)"/g)].map(m=>m[1]).filter(p=>!p.startsWith('/')&&!/(ui|pixel|sharecard|scenes)\.js$/.test(p));
files.forEach(run);
const J = ctx.JY, draws = [];
const pen = new Proxy({font:'',measureText:s=>({width:Array.from(String(s)).length*12}),fillText(s,x,y){draws.push({s:String(s),x,y,font:this.font});}}, {get:(o,k)=>k in o?o[k]:()=>{}});
const canvas = ()=>({getContext:()=>pen});
ctx.document = {createElement:canvas};ctx.location={protocol:'file:'};J.drawPortrait=()=>{};
run('../share/sharecard.js');
const life = {id:'test',name:'沈语桐',book:'西南',sex:'女',born:2026,from:2026,to:2087,deathLoc:'家',cause:'寿终正寝',birthplace:'贵州省 贵阳市下面的一个村子',info:{学历:'本科',职业:'社区兴趣课主理人'},end:{k:'homeward',t:'归园田居',d:'在外面闯过，最后回了老家。'},review:'你亲手把另一种日子过成了日常。',dev:6,picks:[],marks:{},changes:[],words:'别哭，都挺好的。',fateText:'同出身比较文本'};
const story = J.GAME.share.story(life);
assert.equal(story.death,'在家中安然离世');
assert.equal(J.GAME.share.story({...life,to:2106}).death,'寿终正寝于家中');
assert.equal(J.GAME.share.story({...life,cause:'因病去世',deathLoc:'医院'}).death,'因病去世 · 卒于医院');
assert.equal(J.GAME.share.story({...life,deathLoc:''}).death,'安然离世');
const draw=l=>{draws.length=0;J.drawShareCard(canvas(),l);return [...draws];};
const rows = draw(life), title=rows.find(r=>r.s==='归园田居'), metric=rows.find(r=>r.s==='与众不同 6%');
assert(title&&metric);assert.match(title.font,/32px/);assert.match(metric.font,/14px/);assert(title.y<metric.y);
assert.equal(rows.filter(r=>r.s==='这一生的结局').length,1);
assert(!rows.some(r=>r.s==='结局'||r.s==='6%'||r.s.includes('这一生的结局：')||r.s.includes('同出身比较文本')));
assert(rows.some(r=>r.s==='在家中安然离世'));assert(rows.some(r=>r.s.includes('别哭')));
const summary=J.shareText(life,'',false);assert.equal((summary.match(/这一生的结局：/g)||[]).length,1);assert(summary.indexOf('归园田居')<summary.indexOf('与众不同'));
const old={...life};delete old.end;delete old.review;
assert(!draw(old).some(r=>r.s==='这一生的结局'||r.s==='归园田居'));
delete J.GAME.share.story;run('../share/sharecard.js');
assert(draw(life).some(r=>r.s==='6%'&&r.font.includes('84px')),'未设置钩子时保留原卡片');
console.log('PASS 分享卡结局优先、单一结局、离世文案年龄边界、旧档兼容和默认布局');
