/* 家庭记忆只续接实际对象，且不改变选择、费用和属性。 */
'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert/strict');
const root=path.join(__dirname,'..'),store={};
const ctx={console,Math:Object.create(Math),JSON,Date,localStorage:{getItem:k=>store[k]||null,setItem:(k,v)=>{store[k]=v;},removeItem:k=>{delete store[k];}}};
ctx.window=ctx;vm.createContext(ctx);
const files=[...fs.readFileSync(path.join(root,'index.html'),'utf8').matchAll(/<script src="([^"]+)"/g)].map(m=>m[1]).filter(s=>!s.startsWith('/')&&!/(ui|pixel|sharecard|scenes)\.js$/.test(s));
for(const s of files)vm.runInContext(fs.readFileSync(path.join(root,s),'utf8'),ctx);
const J=ctx.JY,E=J.engine;E.startRandom();const g=E.G,L=E.get().L;L.year=J.byId[L.cid].born+79;E.get().W.year=L.year;
const n=id=>J.LIFE_NODES.find(x=>x.id===id),text=id=>typeof n(id).text==='function'?n(id).text(g):n(id).text;
g.spawn({id:'k1',name:'长女',sex:'女',born:g.Y-48});g.spawn({id:'k2',name:'次子',sex:'男',born:g.Y-45});
g.remember('kids',2);g.remember('liveWith','alone');g.remember('kidCity','国外');
const choiceCount=n('o_care_plan').choices.length,stats=JSON.stringify(L.st);
g.remember('familyWork','budget');const plan=text('o_care_plan'),care=text('o_care_echo');
assert(plan.includes('先问你怎么打算'));assert(care.includes('第一份工资'));
g.remember('familyWork','alone');assert.notEqual(text('o_care_plan'),plan);assert.notEqual(text('o_care_echo'),care);
g.remember('familyTeen','listen');const visit=text('o_kids_visit');assert(visit.includes('仍会等对方讲完'));
g.remember('familyTeen','later');assert.notEqual(text('o_kids_visit'),visit);assert(text('o_kids_visit').includes('报名表'));
assert.equal(n('o_care_plan').choices.length,choiceCount);assert.equal(JSON.stringify(L.st),stats,'文字不修改属性');
J.CN.marry(g);g.remember('familyPartner','talk');const birthday=text('o_seventy'),sick=text('o_spcare_echo');
assert(birthday.includes('饭后慢慢说话'));assert(sick.includes('饭后慢慢说话'));
g.remember('familyPartner','space');assert.notEqual(text('o_seventy'),birthday);assert.notEqual(text('o_spcare_echo'),sick);
g.remember('love','widowed');g.remember('remarried',true);g.spawn({id:'sp2',name:'晚年伴侣',sex:'男',born:g.Y-75});
assert(!text('o_seventy').includes('各自喜欢的事还留着'),'再婚不继承原配记忆');
delete J.byId.sib0;delete J.byId.sib1;g.spawn({id:'sib0',name:'姐姐',sex:'女',born:g.Y-81});g.remember('familySibling','share');
assert(text('o_seventy').includes('复查日期'));
g.spawn({id:'sib1',name:'弟弟',sex:'男',born:g.Y-76});assert(!text('o_seventy').includes('复查日期'),'多手足无身份记录时不猜对象');
g.kill('k1','测试',true);assert(!text('o_care_plan').includes('第一份工资'),'长女记忆不套给次子');assert(!text('o_kids_visit').includes('报名表'));
g.kill('k2','测试',true);assert.equal(n('o_kids_visit').cond(g),false,'无健在孩子不触发探望');
console.log('第二批家庭：亲子/夫妻多节点、照护商量、再婚/多子女/手足身份、费用属性不变通过');
