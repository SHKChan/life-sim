'use strict';
const assert = require('assert/strict'), fs = require('fs'), path = require('path'), cp = require('child_process');
const out = path.join(__dirname, '../docs/validation/p0-metrics-check.json');
fs.mkdirSync(path.dirname(out), {recursive:true});
cp.execFileSync(process.execPath, [path.join(__dirname,'compare.js'), '2', out], {env:{...process.env,COMPARE_STYLE:'auto',COMPARE_FILTER:'auto:def',COMPARE_WARN:''}, stdio:'pipe'});
const rows=JSON.parse(fs.readFileSync(out,'utf8')), meta=JSON.parse(fs.readFileSync(out+'.meta.json','utf8'));
assert.equal(rows.length,1);
const r=rows[0], p=r.pace;
assert.equal(r.n,2);
assert.equal(Math.round(Object.values(p.askedByAge).reduce((a,b)=>a+b,0)*100)/100,r.asked);
assert.equal(Object.values(p.askedNodes).reduce((a,b)=>a+b,0)/r.n,r.asked);
assert.ok(p.askedMedian>=0 && p.askedP90>=0);
assert.ok(p.sameYearMax>=1 && p.autoPicks>0 && p.echoLogs>0);
assert.ok(p.echoesWithChoiceSource<=p.echoLogs);
assert.ok(p.completeLives.n>=0 && p.completeLives.n<=r.n);
assert.equal(meta.seedStart,17001); assert.equal(meta.seedEnd,17002);
assert.equal(meta.environment.COMPARE_STYLE,'auto');
assert.equal(meta.toolHash.length,64); assert.ok(meta.scripts.length>5);
console.log('P0节奏统计与复现元数据检查通过');
